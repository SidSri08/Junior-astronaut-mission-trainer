export function getContextualHint(state) {
  const r = state.resources;
  const m = state.modules;
  const hasStorm = state.activeEvents.some((e) => e.eventId === 'solarStorm');
  const hasLeak = state.activeEvents.some((e) => e.eventId === 'oxygenLeak');

  if (hasStorm && !state.crew.sheltered) {
    return { kind: 'bad', text: '🚨 Solar Storm alert! Click "Shelter Crew" right away to protect your astronauts from radiation!' };
  }
  if (!hasStorm && state.crew.sheltered) {
    return { kind: 'warn', text: '👨‍🚀 The Solar Storm is over! Release the crew from the shelter so the Science Lab can resume work.' };
  }
  if (hasLeak) {
    return { kind: 'bad', text: '💨 Hull air leak active! Play the Leak Hunter minigame or use a Repair Kit to seal it.' };
  }
  if (state.power.brownout) {
    return { kind: 'bad', text: '🔌 Blackout! Switch OFF the Lab or Greenhouse so the solar panels can recharge the battery to 12%.' };
  }
  if (r.oxygen < 35) {
    if (!m.lifeSupport.online) return { kind: 'bad', text: '💨 Oxygen is low and Life Support is OFF! Turn Life Support ON.' };
    if (r.water < 10) return { kind: 'bad', text: '💧 Life Support needs Water to make Oxygen! Send the Rover for crater ice.' };
    return { kind: 'warn', text: '💨 Oxygen is low. Repair Life Support or play Leak Hunter!' };
  }
  if (r.water < 28) {
    return { kind: 'warn', text: '🧊 Water is getting low. Click "Mine Crater Ice" to send the rover for water ice!' };
  }
  if (m.greenhouse.planted && m.greenhouse.growth >= 100) {
    return { kind: 'good', text: '🥬 Greenhouse crops are 100% grown! Click "Harvest Crops" for +30% Food.' };
  }
  if (r.battery < 30 && state.power.net < 0) {
    return { kind: 'warn', text: '🔋 Battery is draining! Play Solar Aligner to boost solar power, or turn off the Lab temporarily.' };
  }
  if (m.solar.dust > 0.35 || m.solar.alignment < 0.75) {
    return { kind: 'info', text: '☀️ Tip: Your solar panels have Moon dust or tilt error. Play "Solar Aligner" for maximum power!' };
  }
  if (state.shieldLevel === 0 && state.mission.day >= 2) {
    return { kind: 'info', text: '⛏️ Tip: Upgrade Regolith Shielding on the Habitat before Day 4’s solar storm!' };
  }
  return { kind: 'info', text: '🌟 Outpost running smoothly! Keep collecting Research Points in the Science Lab.' };
}

